"""
    Geometry

Quantities derived from the body state that energy terms and kernels read:

- `lab`: `ncoef × N` lab-frame coefficients `[a₀; αₙ; βₙ]`
- `R`, `dR`, `ddR`: `nθ × N` contour radius and its first two φ-derivatives
  at the quadrature nodes
- `rmax`: upper bound of R(φ) per body, R₀(a₀ + Σₙ √(aₙ² + bₙ²))
"""
struct Geometry{V <: AbstractVector, Mat <: AbstractMatrix}
    lab::Mat
    R::Mat
    dR::Mat
    ddR::Mat
    rmax::V
end

function Geometry(basis::FourierBasis, bodies::Bodies)
    N = nbodies(bodies)
    T = eltype(bodies.x)
    backend = get_backend(bodies.x)
    alloc(dims...) = KernelAbstractions.zeros(backend, T, dims...)
    return Geometry(alloc(ncoef(basis), N), alloc(basis.nθ, N), alloc(basis.nθ, N),
        alloc(basis.nθ, N), alloc(N))
end

# Coefficient layout (all `ncoef × N` matrices): column i belongs to body i,
# row 1 holds a₀, rows 1+m and 1+K+m hold the cosine and sine coefficients of
# mode n = m + 1 (m = 1, …, K, K = number of shape modes).

# Rotate body-frame coefficients into the lab frame and bound the contour radius.
# One work item per body i.
#
#   lab   (out) ncoef × N lab-frame coefficients [a₀; αₙ; βₙ]
#   rmax  (out) N, upper bound of Rᵢ(φ)
#   coef  ncoef × N body-frame coefficients [a₀; aₙ; bₙ]
#   θ     N, body orientations
#   R0    N, body radius scales
#   K     number of shape modes (n = 2, …, K + 1)
#
# Maths: the body-frame contour uses cos n(φ-θ) and sin n(φ-θ). With the angle
# addition formulas
#   cos n(φ-θ) = cos nφ cos nθ + sin nφ sin nθ
#   sin n(φ-θ) = sin nφ cos nθ - cos nφ sin nθ
# each mode becomes
#   aₙ cos n(φ-θ) + bₙ sin n(φ-θ) = αₙ cos nφ + βₙ sin nφ  with
#   αₙ = aₙ cos nθ - bₙ sin nθ,   βₙ = aₙ sin nθ + bₙ cos nθ,
# i.e. (aₙ, bₙ) rotated by the angle nθ. The lab-frame form has θ-independent
# basis functions, so one synthesis matrix serves all bodies.
#
# Bound: |aₙ cos + bₙ sin| ≤ √(aₙ² + bₙ²) (Cauchy–Schwarz), hence
# R ≤ R₀ (a₀ + Σₙ √(aₙ² + bₙ²)). The rotation preserves √(aₙ² + bₙ²).
@kernel function lab_frame_kernel!(lab, rmax, @Const(coef), @Const(θ), @Const(R0), K)
    i = @index(Global)
    lab[1, i] = coef[1, i]
    bound = coef[1, i]
    for m in 1:K
        n = m + 1
        a = coef[1 + m, i]
        b = coef[1 + K + m, i]
        s, c = sincos(n * θ[i])
        lab[1 + m, i] = a * c - b * s
        lab[1 + K + m, i] = a * s + b * c
        bound += sqrt(a^2 + b^2)
    end
    rmax[i] = R0[i] * bound
end

"""
    update_geometry!(geom, basis, bodies)

Rotate coefficients into the lab frame and synthesise the contours of all
bodies at the quadrature nodes: R = R₀ ⋅ (C · lab) and likewise for R', R''
with the derivative matrices D, DD (three dense matrix products, `nθ × ncoef`
times `ncoef × N`, followed by scaling column i by R₀ᵢ).
"""
function update_geometry!(geom::Geometry, basis::FourierBasis, bodies::Bodies)
    backend = get_backend(bodies.x)
    lab_frame_kernel!(backend, WORKGROUP)(geom.lab, geom.rmax, bodies.coef, bodies.θ,
        bodies.R0, nmodes(basis); ndrange = nbodies(bodies))
    R0row = reshape(bodies.R0, 1, :)
    mul!(geom.R, basis.C, geom.lab)
    geom.R .*= R0row
    mul!(geom.dR, basis.D, geom.lab)
    geom.dR .*= R0row
    mul!(geom.ddR, basis.DD, geom.lab)
    geom.ddR .*= R0row
    return geom
end

"""
    contour_radius(lab, j, R0, K, ψ)

Evaluate R_j(ψ) = R0 [a₀ + Σₙ αₙ cos nψ + βₙ sin nψ] of body `j` at an
arbitrary lab-frame angle `ψ`, from the lab-frame coefficients `lab` (column
`j`), radius scale `R0` and number of shape modes `K`. Used in kernels to test
whether a point lies inside body j.

Instead of one `sincos` per mode, cos nψ and sin nψ are generated by the angle
addition formulas for (n+1)ψ = nψ + ψ:

    cos (n+1)ψ = cos nψ cos ψ - sin nψ sin ψ
    sin (n+1)ψ = sin nψ cos ψ + cos nψ sin ψ

i.e. repeated rotation of (cos nψ, sin nψ) by ψ.
"""
@inline function contour_radius(lab, j, R0, K, ψ)
    s1, c1 = sincos(ψ)
    # (c, s) holds (cos nψ, sin nψ); start at n = 1, the loop advances to n = m + 1
    c, s = c1, s1
    r = lab[1, j]
    for m in 1:K
        c, s = c * c1 - s * s1, s * c1 + c * s1
        r += lab[1 + m, j] * c + lab[1 + K + m, j] * s
    end
    return R0 * r
end
